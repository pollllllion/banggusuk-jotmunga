const ALL = () => [...PERSONAS, ...OTHER_PERSONAS]
export const personaByKey = key => ALL().find(p => p.key === key) || null
/** 원고의 P-ID 로 찾는다 — 올리는 쪽은 이 함수만 쓰면 작성자를 고를 일이 없다 */
export const personaById = id => PERSONAS.find(p => p.id === String(id).toUpperCase()) || null
export const personaEmail = key => `${key}@${PERSONA_DOMAIN}`

/**
 * 큐의 `as` 값을 페르소나로 바꾼다 — P-ID("P04") · 키("director") · 닉네임("404") 다 받는다.
 * 원고가 `POST 01 — P04 / 404` 로 오므로 큐에 P-ID 를 그대로 적어도 되게 하려는 것이다.
 * 홍인기 몫 8개(OTHER_PERSONAS)도 키·닉네임으로 찾힌다. P-ID 는 그쪽에 없다.
 */
export const resolvePersona = ref => {
  const s = String(ref || '').trim()
  return personaById(s) || personaByKey(s) || ALL().find(p => p.nick === s) || null
}
