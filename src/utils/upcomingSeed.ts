/**
 * 개봉/공개 예정작 시드 데이터 (캘린더 초기 채움용)
 *
 * ⚠️ 임시 시드입니다. 실제 운영에서는 KOBIS(영진위) 개봉예정 API·OTT 스케줄·
 *    웹툰/웹소설 신작 정보를 어드민으로 입력하거나 수집 스크립트로 채웁니다.
 *    Supabase contents 테이블에 releaseDate 컬럼이 채워지기 시작하면
 *    이 시드는 제거하면 됩니다. (dataService.loadAll 에서 title 중복은 자동 스킵)
 *
 * 날짜는 2026년 하반기 기준으로, 오늘(개발 시점) 이후로 배치해 "예정작"으로 보이게 했습니다.
 */
function seed(
  id: string,
  type: Content['type'],
  title: string,
  releaseDate: string,
  platform: string,
  genres: string[],
  creators: string[],
  synopsis: string,
): Content {
  return {
    id: `seed-${id}`,
    type,
    title,
    posterUrl: null,
    synopsis,
    genres,
    creators,
    platform,
    releaseYear: Number(releaseDate.slice(0, 4)),
    releaseDate,
    status: 'upcoming',
    popularity: 0,
    avgRating: 0,
    reviewCount: 0,
    createdBy: 'seed',
    createdAt: '2026-07-01T00:00:00.000Z',
  }
}

