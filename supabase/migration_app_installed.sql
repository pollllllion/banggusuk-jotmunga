-- ============================================================
-- 앱 설치 기록 — profiles 에 appInstalledOn 칸 추가
-- 2026-09-14
-- ============================================================
-- 무엇을:
--   "appInstalledOn" — 이 계정이 앱(홈 화면)으로 연 적이 있는 기기 종류.
--   'ios' | 'android' | 'desktop' 의 배열. 없으면(null) 기록 없음.
--
-- 왜 계정에 적나:
--   아이폰은 사파리와 홈 화면 앱이 저장소를 따로 쓴다. 앱에서 남긴 표시를
--   사파리가 읽지 못하고, 크롬처럼 '이미 설치됨'을 알려주는 신호도 없다.
--   그래서 앱으로 열렸을 때 계정에 적어 두고, 같은 계정으로 사파리에 오면
--   설치 권유 배너를 띄우지 않는다. 로그인하지 않은 사람은 구분할 수 없다.
--
-- 배포 순서:
--   아무 쪽이 먼저여도 된다. 칸이 없으면 기록 저장만 조용히 실패하고 배너는 예전처럼 뜬다.
--
-- 권한:
--   profiles_update 정책이 이미 '본인 행만'이라 따로 손댈 것이 없다.
--
-- 실행: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run.
-- ============================================================

alter table public.profiles
  add column if not exists "appInstalledOn" text[];

