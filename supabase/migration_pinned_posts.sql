-- ============================================================
-- 내 토론 — 내가 고른 내 글 모음 (profiles 에 칸 하나)
-- 2026-09-10
-- ============================================================
-- 무엇을:
--   "pinnedPosts" — 내가 쓴 글 중 내 피드에 걸어 둘 것들.
--   [{"id": "<discussion id>", "public": true}, ...] 차례 있는 배열.
--
-- 왜 jsonb 인가 (text[] 가 아니라):
--   글마다 공개/비공개가 따로 있다. id 배열과 '공개인 id 배열' 을 따로 두면 둘이 어긋난다
--   (한쪽에서 지웠는데 다른 쪽에 남는 식). 한 칸에 붙여 둔다.
--   차례도 이 배열이 그대로 화면 차례다 — 고른 사람이 정한 순서다.
--
-- 왜 profiles 인가 (discussions 에 플래그가 아니라):
--   '어떤 글이 걸려 있나' 는 글의 성질이 아니라 그 사람의 선택이고, 순서가 있다.
--   글 표에 두면 순서를 담을 곳이 없고, 목록을 만들 때마다 글 전체를 훑어야 한다.
--
-- 왜 추가형인가 (배포 순서 주의):
--   기본값이 있어 **마이그레이션을 먼저** 돌리고 배포해야 한다.
--   칸이 없는 상태로 새 코드가 뜨면 저장이 400 으로 떨어진다.
--   반대로 이 SQL 을 먼저 돌려도 지금 떠 있는 옛 코드는 이 칸을 안 보내므로 아무 일도 안 생긴다.
--
-- 권한: profiles_update 정책이 이미 '본인 행만' 이라 따로 손댈 것이 없다.
--
-- 실행: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run.
-- ============================================================

alter table public.profiles
  add column if not exists "pinnedPosts" jsonb not null default '[]'::jsonb;

