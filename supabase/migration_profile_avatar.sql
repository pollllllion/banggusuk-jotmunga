-- ============================================================
-- 프로필 사진 — profiles 에 avatarUrl 칸 추가
-- 2026-09-10
-- ============================================================
-- 무엇을:
--   "avatarUrl" — 업로드한 프로필 사진의 공개 URL. 없으면(null) 빈 사람 실루엣이 뜬다.
--
-- 어디에 저장하나:
--   그림 파일 자체는 이미 있는 **talk-media 버킷**에 `avatars/` 아래로 올린다
--   (migration_talk_media.sql 이 만든 버킷 · 읽기 공개 / 쓰기는 로그인 사용자).
--   버킷을 새로 만들지 않는 이유는 정책을 한 벌 더 관리할 일이 없어서다.
--   DB 에는 주소만 담는다 — base64 를 컬럼에 넣으면 profiles 가 시작 로드에
--   통째로 실려 오므로 사람 수만큼 첫 화면이 무거워진다.
--
-- 왜 추가형인가 (배포 순서 주의):
--   기본값이 null 이라 **마이그레이션을 먼저** 돌리고 배포해야 한다.
--   칸이 없는 상태로 새 코드가 뜨면 사진 저장이 400 으로 떨어진다.
--   반대로 이 SQL 을 먼저 돌려도 지금 떠 있는 옛 코드는 이 칸을 안 보내므로 아무 일도 안 생긴다.
--
-- 권한:
--   profiles_update 정책이 이미 '본인 행만'이라 따로 손댈 것이 없다.
--   (닉네임·알림·취향을 같은 길로 고치고 있다 — api/users.ts 의 updateProfileRow)
--
-- 실행: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run.
-- ============================================================

alter table public.profiles
  add column if not exists "avatarUrl" text;

